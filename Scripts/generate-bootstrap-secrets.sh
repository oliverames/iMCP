#!/bin/bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
OUTPUT_PATH="$REPO_ROOT/Shared/Mobile/GeneratedBootstrapSecrets.swift"

if [[ "${IMCP_SKIP_1PASSWORD:-0}" != "1" ]] && command -v op >/dev/null 2>&1; then
    if BOOTSTRAP_JSON="$(op item get "iMCP Dev Bootstrap" --vault Development --format json 2>/dev/null)"; then
        CERT_ITEM_ID="$(printf '%s' "$BOOTSTRAP_JSON" | python3 -c '
import json, sys
item = json.load(sys.stdin)
for f in item.get("fields", []):
    if f.get("label") == "cloudflare_cert_item_id" and f.get("value"):
        print(f["value"])
        break
')"
        CF_PEM_B64=""
        if [[ -n "$CERT_ITEM_ID" ]]; then
            CF_PEM_B64="$(
                (op document get "$CERT_ITEM_ID" --vault Development 2>/dev/null || true) | base64 | tr -d '\n'
            )"
            if [[ -z "$CF_PEM_B64" ]]; then
                CF_PEM_B64="$(
                    op item get "$CERT_ITEM_ID" --vault Development --format json 2>/dev/null | python3 -c '
import base64, json, sys
raw = sys.stdin.read().strip()
if not raw:
    sys.exit(0)
item = json.loads(raw)
for f in item.get("fields", []):
    if (f.get("id") == "notesPlain" or f.get("label") == "notesPlain") and f.get("value"):
        print(base64.b64encode(f["value"].encode("utf-8")).decode("ascii"), end="")
        break
' || true
                )"
            fi
        fi

        IMCP_BOOTSTRAP_JSON="$BOOTSTRAP_JSON" IMCP_CF_PEM_B64="$CF_PEM_B64" python3 - "$OUTPUT_PATH" <<'PYEOF'
import json
import os
import sys

out_path = sys.argv[1]
bootstrap = json.loads(os.environ["IMCP_BOOTSTRAP_JSON"])
fields = {f.get("label"): f.get("value", "") for f in bootstrap.get("fields", []) if f.get("label")}
cf_pem_b64 = os.environ.get("IMCP_CF_PEM_B64", "").strip()

def swift_escape(value: str) -> str:
    return (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
    )

device_id = fields.get("mobile_device_id", "")
device_name = fields.get("mobile_device_name", "")
device_key = fields.get("mobile_device_key", "")
bonjour_service = fields.get("mac_bonjour_service", "")
tailnet_host = fields.get("tailnet_host", "")
tailnet_ip = fields.get("tailnet_ip", "")
tailnet_port_str = fields.get("tailnet_mobile_port", "4628") or "4628"
try:
    tailnet_port = int(tailnet_port_str)
except ValueError:
    tailnet_port = 4628
funnel_url = fields.get("funnel_url", "")
funnel_mobile_url = fields.get("funnel_mobile_url", "")
cf_hostname = fields.get("cloudflare_hostname", "")
cf_mobile_url = fields.get("cloudflare_mobile_url", "")
cf_tunnel_id = fields.get("cloudflare_tunnel_id", "")
cf_tunnel_token = fields.get("cloudflare_tunnel_token", "")
cf_tunnel_name = fields.get("cloudflare_tunnel_name", "") or "imcp-macbook-pro"

is_configured = "true" if (device_id and device_key) else "false"

content = f"""// Generated by Scripts/generate-bootstrap-secrets.sh. Do not commit.
import Foundation

enum DevBootstrapSecrets {{
    static let isConfigured: Bool = {is_configured}
    static let mobileDeviceID: String = "{swift_escape(device_id)}"
    static let mobileDeviceName: String = "{swift_escape(device_name)}"
    static let mobileDeviceKeyBase64: String = "{swift_escape(device_key)}"
    static let macBonjourService: String = "{swift_escape(bonjour_service)}"
    static let tailnetHost: String = "{swift_escape(tailnet_host)}"
    static let tailnetIP: String = "{swift_escape(tailnet_ip)}"
    static let tailnetMobilePort: UInt16 = {tailnet_port}
    static let funnelURL: String = "{swift_escape(funnel_url)}"
    static let funnelMobileURL: String = "{swift_escape(funnel_mobile_url)}"
    static let cloudflareHostname: String = "{swift_escape(cf_hostname)}"
    static let cloudflareMobileURL: String = "{swift_escape(cf_mobile_url)}"
    static let cloudflareTunnelID: String = "{swift_escape(cf_tunnel_id)}"
    static let cloudflareTunnelName: String = "{swift_escape(cf_tunnel_name)}"
    static let cloudflareTunnelToken: String = "{swift_escape(cf_tunnel_token)}"
    static let cloudflareCertPEMBase64: String = "{swift_escape(cf_pem_b64)}"
}}
"""

tmp_path = out_path + ".tmp"
fd = os.open(tmp_path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
with os.fdopen(fd, "w", encoding="utf-8") as handle:
    handle.write(content)
os.replace(tmp_path, out_path)
PYEOF
        echo "Generated Shared/Mobile/GeneratedBootstrapSecrets.swift from 1Password."
        exit 0
    fi
fi

cat > "$OUTPUT_PATH" <<'EOF'
// Generated by Scripts/generate-bootstrap-secrets.sh. Do not commit.
import Foundation

enum DevBootstrapSecrets {
    static let isConfigured: Bool = false
    static let mobileDeviceID: String = ""
    static let mobileDeviceName: String = ""
    static let mobileDeviceKeyBase64: String = ""
    static let macBonjourService: String = ""
    static let tailnetHost: String = ""
    static let tailnetIP: String = ""
    static let tailnetMobilePort: UInt16 = 4628
    static let funnelURL: String = ""
    static let funnelMobileURL: String = ""
    static let cloudflareHostname: String = ""
    static let cloudflareMobileURL: String = ""
    static let cloudflareTunnelID: String = ""
    static let cloudflareTunnelName: String = ""
    static let cloudflareTunnelToken: String = ""
    static let cloudflareCertPEMBase64: String = ""
}
EOF
chmod 600 "$OUTPUT_PATH"
echo "Generated fallback Shared/Mobile/GeneratedBootstrapSecrets.swift (no 1Password session)."
